"use client";

import { useCallback } from "react";
import { Download } from "lucide-react";
import { forecastData } from "@/data/forecast";
import { downloadCsv, downloadJson } from "@/components/dashboard/downloadUtils";

const ICON_BTN = "flex h-7 w-7 items-center justify-center rounded-lg border border-slate-700 text-slate-400 transition-colors hover:border-cyan-500 hover:text-cyan-300";

interface DatasetCardProps {
  name: string;
  description: string;
  source: string;
  format: string;
  onDownload: () => void;
}

function DatasetCard({ name, description, source, format, onDownload }: DatasetCardProps) {
  return (
    <div className="rounded-xl border border-slate-800 bg-slate-950/60 p-4">
      <div className="flex items-start justify-between gap-3">
        <div className="flex-1 min-w-0">
          <h3 className="text-sm font-semibold text-white">{name}</h3>
          <p className="mt-1 text-xs text-slate-400 leading-relaxed">{description}</p>
          <p className="mt-2 text-[10px] text-slate-500">
            Source: <span className="text-slate-400">{source}</span> &middot; Format: <span className="text-slate-400">{format}</span>
          </p>
        </div>
        <button
          onClick={onDownload}
          className={ICON_BTN}
          aria-label={`Download ${name}`}
          title={`Download ${format}`}
        >
          <Download size={14} />
        </button>
      </div>
    </div>
  );
}

export default function DataSourcesPage() {
  const { meta, historical, oni, maps, regionalRisk } = forecastData;

  const downloadHistorical = useCallback(() => {
    const rows = historical.map((h) => ({ time: h.time, value: h.value }));
    downloadCsv(rows, `oni-historical-${Date.now()}.csv`);
  }, [historical]);

  const downloadForecast = useCallback(() => {
    const rows = oni.rows.map((r) => ({
      month: r.month,
      seed0: r.seeds[0],
      seed1: r.seeds[1],
      seed2: r.seeds[2],
      seed3: r.seeds[3],
      seed4: r.seeds[4],
      ensMean: r.ensMean,
      ensStd: r.ensStd,
    }));
    downloadCsv(rows, `oni-forecast-ensemble-${Date.now()}.csv`);
  }, [oni]);

  const downloadTempGrid = useCallback(() => {
    downloadJson({
      months: maps.months,
      lats: maps.lats,
      lons: maps.lons,
      t2mMean: maps.t2mMean,
    }, `temperature-anomaly-grid-${Date.now()}.json`);
  }, [maps]);

  const downloadPrecipGrid = useCallback(() => {
    downloadJson({
      months: maps.months,
      lats: maps.lats,
      lons: maps.lons,
      tpMean: maps.tpMean,
    }, `precipitation-anomaly-grid-${Date.now()}.json`);
  }, [maps]);

  const downloadRegionalRisk = useCallback(() => {
    const rows = Object.entries(regionalRisk).flatMap(([month, risks]) =>
      risks.map((r) => ({
        month,
        country: r.country,
        tempAnomaly: r.t2mZ,
        precipAnomaly: r.tpZ,
        risk: r.risk,
      }))
    );
    downloadCsv(rows, `regional-risk-${Date.now()}.csv`);
  }, [regionalRisk]);

  const downloadMeta = useCallback(() => {
    downloadJson(meta, `forecast-meta-${Date.now()}.json`);
  }, [meta]);

  return (
    <div className="rounded-2xl border border-slate-800/90 bg-slate-900/90 p-5 shadow-2xl shadow-cyan-950/10 sm:p-8">
      <p className="text-xs font-semibold tracking-[0.18em] text-cyan-400">
        DATA &amp; SOURCES
      </p>
      <h2 className="mt-3 text-xl font-bold tracking-tight text-white">
        Data Sources &amp; Downloads
      </h2>
      <p className="mt-2 text-sm text-slate-400">
        Download the raw datasets powering this dashboard. All data is generated by the CNN-TCN ensemble model.
      </p>

      <div className="mt-6 grid gap-4 sm:grid-cols-2">
        <DatasetCard
          name="ONI Historical Series"
          description={`Monthly Ni\u00f1o 3.4 ONI values from ${historical[0]?.time?.slice(0, 7)} through ${historical[historical.length - 1]?.time?.slice(0, 7)} (${historical.length} data points).`}
          source="Internal / model input"
          format="CSV"
          onDownload={downloadHistorical}
        />
        <DatasetCard
          name="ONI Forecast Ensemble"
          description={`Ensemble forecast for ${oni.months.slice(0, -1).join(", ")} with ${oni.rows[0]?.seeds.length ?? 0} seed members, ensemble mean, and standard deviation.`}
          source="Internal / CNN-TCN model output"
          format="CSV"
          onDownload={downloadForecast}
        />
        <DatasetCard
          name="Temperature Anomaly Grid"
          description={`Gridded 2m temperature z-scores: ${maps.months.length} months \u00d7 ${maps.lats.length}\u00d7${maps.lons.length} cells (lat ${maps.lats[0]}\u2013${maps.lats[maps.lats.length - 1]}, lon ${maps.lons[0]}\u2013${maps.lons[maps.lons.length - 1]}).`}
          source="Internal / CNN-TCN model output"
          format="JSON"
          onDownload={downloadTempGrid}
        />
        <DatasetCard
          name="Precipitation Anomaly Grid"
          description={`Gridded total precipitation z-scores: ${maps.months.length} months \u00d7 ${maps.lats.length}\u00d7${maps.lons.length} cells.`}
          source="Internal / CNN-TCN model output"
          format="JSON"
          onDownload={downloadPrecipGrid}
        />
        <DatasetCard
          name="Regional Risk Data"
          description="Per-country composite risk assessment for Nepal, India, and Bangladesh (temperature/precipitation anomalies, risk level)."
          source="Internal / computed from grid data"
          format="CSV"
          onDownload={downloadRegionalRisk}
        />
        <DatasetCard
          name="Forecast Metadata"
          description={`Configuration: ${meta.nMembers} ensemble members, ${meta.leadMonths}-month lead, ${meta.seqLen}-month sequence, grid ${meta.grid.ws}\u00d7${meta.grid.hs}.`}
          source="Internal / generation config"
          format="JSON"
          onDownload={downloadMeta}
        />
      </div>

      <div className="mt-6 rounded-xl border border-slate-800 bg-slate-950/60 p-4">
        <h3 className="text-sm font-semibold text-white">Static Forecast Files</h3>
        <p className="mt-1 text-xs text-slate-400">
          Pre-generated forecast outputs available for direct download:
        </p>
        <div className="mt-3 flex flex-wrap gap-2">
          <a
            href="/forecast/ensemble_oni_2026.csv"
            download
            className="inline-flex items-center gap-1.5 rounded-lg border border-slate-700 px-3 py-1.5 text-xs text-slate-300 transition-colors hover:border-cyan-500 hover:text-cyan-300"
          >
            <Download size={12} /> ONI CSV
          </a>
          <a
            href="/forecast/ensemble_maps_2026.npz"
            download
            className="inline-flex items-center gap-1.5 rounded-lg border border-slate-700 px-3 py-1.5 text-xs text-slate-300 transition-colors hover:border-cyan-500 hover:text-cyan-300"
          >
            <Download size={12} /> Maps NPZ
          </a>
          <a
            href="/forecast/forecast_meta.json"
            download
            className="inline-flex items-center gap-1.5 rounded-lg border border-slate-700 px-3 py-1.5 text-xs text-slate-300 transition-colors hover:border-cyan-500 hover:text-cyan-300"
          >
            <Download size={12} /> Metadata JSON
          </a>
        </div>
      </div>

      <div className="mt-6 rounded-xl border border-slate-800 bg-slate-950/60 p-4">
        <h3 className="text-sm font-semibold text-white">Map Boundaries</h3>
        <p className="mt-1 text-xs text-slate-400">
          Country boundaries sourced from Natural Earth via the <code className="text-slate-300">world-atlas</code> npm package (countries-50m TopoJSON resolution).
        </p>
      </div>
    </div>
  );
}
